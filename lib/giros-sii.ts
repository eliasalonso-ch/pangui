function aObjeto(t: GiroTupla): Giro {
  return { codigo: t[0], nombre: t[1], afectoIva: t[2], categoria: t[3] };
}

/** Busca por código exacto. */
export function giroPorCodigo(codigo: string): Giro | null {
  const t = GIROS_SII.find(g => g[0] === codigo);
  return t ? aObjeto(t) : null;
}

/**
 * Etiqueta que se guarda en billing_profiles.giro y se imprime en la factura:
 * "620100 - ACTIVIDADES DE PROGRAMACIÓN INFORMÁTICA".
 */
export function etiquetaGiro(giro: GiroTupla | Giro): string {
  return Array.isArray(giro)
    ? `${giro[0]} - ${giro[1]}`
    : `${(giro as Giro).codigo} - ${(giro as Giro).nombre}`;
}

/** Extrae el código de una etiqueta guardada ("620100 - ...") → "620100". */
export function codigoDesdeEtiqueta(valor: string | null | undefined): string | null {
  const m = (valor ?? "").match(/^(\d{6})\b/);
  return m ? m[1] : null;
}

/** Quita tildes y pasa a minúsculas, para que "informatica" encuentre "INFORMÁTICA". */
function normalizar(texto: string): string {
  return texto.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

/**
 * Filtra por código o por palabras del nombre. Cada palabra debe aparecer, en
 * cualquier orden: "venta computadores" encuentra "VENTA AL POR MENOR DE
 * COMPUTADORES...".
 */
export function buscarGiros(consulta: string, limite = 50): Giro[] {
  const q = normalizar(consulta).trim();
  if (!q) return GIROS_SII.slice(0, limite).map(aObjeto);

  const palabras = q.split(/\s+/);
  const res: Giro[] = [];
  for (const t of GIROS_SII) {
    const heno = normalizar(`${t[0]} ${t[1]}`);
    if (palabras.every(p => heno.includes(p))) {
      res.push(aObjeto(t));
      if (res.length >= limite) break;
    }
  }
  return res;
}
